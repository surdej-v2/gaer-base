// /admin/shop/print — a sheet of QR labels to print and put next to the goods. No admin chrome.
// ?ids=1,2 prints those products; without ids every product for sale.
import { useState } from "react";
import { api } from "../../api";
import { Alert, Loading, useLoad } from "../../ui";
import { kr } from "./Shop";

type Label = { id: number; code: string; name: string; price_ore: number; url: string; svg: string };

const SIZES = { small: ["Små (4 pr. række)", "44mm"], medium: ["Mellem (3 pr. række)", "60mm"], large: ["Store (2 pr. række)", "90mm"] } as const;

export default function ShopPrint() {
  const ids = new URLSearchParams(window.location.search).get("ids") ?? "";
  const labels = useLoad(() => api.get<Label[]>(`/api/admin/shop/labels${ids ? `?ids=${encodeURIComponent(ids)}` : ""}`));
  const [size, setSize] = useState<keyof typeof SIZES>("medium");
  const [copies, setCopies] = useState(1);

  const items = (labels.data ?? []).flatMap((l) => Array.from({ length: copies }, (_, i) => ({ ...l, key: `${l.id}-${i}` })));

  return (
    <div className="shop-print" style={{ "--qr": SIZES[size][1] } as React.CSSProperties}>
      <div className="shop-print-bar">
        <a href="/admin/shop">← Butik</a>
        <select value={size} onChange={(e) => setSize(e.target.value as keyof typeof SIZES)}>
          {Object.entries(SIZES).map(([k, [label]]) => <option key={k} value={k}>{label}</option>)}
        </select>
        <label>Kopier <input type="number" min={1} max={50} value={copies} onChange={(e) => setCopies(Math.max(1, Math.min(50, Number(e.target.value) || 1)))} /></label>
        <button className="btn btn-primary" onClick={() => window.print()} disabled={!items.length}>Udskriv</button>
      </div>
      <Alert>{labels.error}</Alert>
      {!labels.data ? <Loading /> : items.length === 0 ? <p className="muted">Ingen varer til salg.</p> : (
        <div className="shop-labels">
          {items.map((l) => (
            <div className="shop-label" key={l.key}>
              <div className="shop-label-name">{l.name}</div>
              <div className="shop-label-price">{kr(l.price_ore)}</div>
              {/* The SVG is generated by the server (segno) from our own product URL. */}
              <div className="shop-label-qr" dangerouslySetInnerHTML={{ __html: l.svg }} />
              <div className="shop-label-cta">Scan og betal med MobilePay</div>
              <div className="shop-label-url">{l.url.replace(/^https?:\/\//, "")}</div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
